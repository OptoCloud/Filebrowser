const (
	thumbSize      = 400
	maxImagePixels = 80_000_000
	maxImageBytes  = 200 << 20
)

var ErrNoThumbnail = errors.New("no thumbnail for this file")

var pureGoImages = map[string]bool{"image/jpeg": true, "image/png": true, "image/gif": true, "image/webp": true, "image/bmp": true}

// CanThumbnail reports whether a thumbnail can be attempted for a MIME type.
func CanThumbnail(mime string) bool {
	return pureGoImages[mime] || strings.HasPrefix(mime, "video/") || strings.HasPrefix(mime, "audio/") ||
		mime == "image/heic" || mime == "image/heif" || mime == "image/avif" || mime == "image/tiff"
}

// Thumbnail returns the path of a cached JPEG thumbnail, generating it lazily.
func (s *Service) Thumbnail(ctx context.Context, path string) (string, error) {
	mime := files.MimeType(path)
	if !CanThumbnail(mime) {
		return "", ErrNoThumbnail
	}
	fi, err := s.fs.Stat(path)
	if err != nil {
		return "", err
	}
	if fi.IsDir() {
		return "", ErrNoThumbnail
	}
	size, mtime := fi.Size(), fi.ModTime().UnixNano()
	if p, err := s.store.Thumbnail(ctx, path, size, mtime); err == nil {
		if _, err := os.Stat(p); err == nil {
			return p, nil
		}
	} else if !errors.Is(err, store.ErrNotFound) {
		return "", err
	}
	key := cacheKey(path, fi, "thumb")
	v, err, _ := s.thumbSF.Do(key, func() (any, error) {
		out, err := s.cachePath("thumbs", key, ".jpg")
		if err != nil {
			return "", err
		}
		if pureGoImages[mime] {
			err = s.thumbImage(ctx, path, out)
		} else {
			err = s.thumbFFmpeg(ctx, path, out, strings.HasPrefix(mime, "video/"))
		}
		if err != nil {
			return "", err
		}
		old, err := s.store.PutThumbnail(context.WithoutCancel(ctx), path, size, mtime, out)
		if old != "" {
			_ = os.Remove(old)
		}
		return out, err
	})
	if err != nil {
		return "", err
	}
	return v.(string), nil
}

func (s *Service) thumbImage(ctx context.Context, path, out string) error {
	select {
	case s.thumbSem <- struct{}{}:
		defer func() { <-s.thumbSem }()
	case <-ctx.Done():
		return ctx.Err()
	}
	f, fi, err := s.fs.OpenFile(path)
	if err != nil {
		return err
	}
	defer f.Close()
	if fi.Size() > maxImageBytes {
		return ErrNoThumbnail
	}
	// Reject decompression bombs before allocating.
	cfg, _, err := image.DecodeConfig(f)
	if err != nil {
		return ErrNoThumbnail
	}
	if cfg.Width <= 0 || cfg.Height <= 0 || int64(cfg.Width)*int64(cfg.Height) > maxImagePixels {
		return ErrNoThumbnail
	}
	if _, err := f.Seek(0, io.SeekStart); err != nil {
		return err
	}
	orientation := 1
	if files.MimeType(path) == "image/jpeg" {
		orientation = jpegOrientation(f)
		if _, err := f.Seek(0, io.SeekStart); err != nil {
			return err
		}
	}
	img, _, err := image.Decode(f)
	if err != nil {
		return ErrNoThumbnail
	}
	b := img.Bounds()
	w, h := fit(b.Dx(), b.Dy(), thumbSize)
	dst := image.NewRGBA(image.Rect(0, 0, w, h))
	draw.ApproxBiLinear.Scale(dst, dst.Bounds(), img, b, draw.Src, nil)
	return writeJPEG(out, orient(dst, orientation))
}

func fit(w, h, box int) (int, int) {
	if w <= box && h <= box {
		return w, h
	}
	if w >= h {
		return box, max(1, h*box/w)
	}
	return max(1, w*box/h), box
}

func writeJPEG(out string, img image.Image) error {
	tmp := out + ".tmp"
	f, err := os.Create(tmp) // #nosec G304 -- cache path generated by the server
	if err != nil {
		return err
	}
	if err := jpeg.Encode(f, img, &jpeg.Options{Quality: 80}); err != nil {
		_ = f.Close()
		_ = os.Remove(tmp)
		return err
	}
	if err := f.Close(); err != nil {
		_ = os.Remove(tmp)
		return err
	}
	return os.Rename(tmp, out)
}

func (s *Service) thumbFFmpeg(ctx context.Context, path, out string, video bool) error {
	seek := 0.0
	if video {
		seek = 5
		if p, err := s.Probe(ctx, path); err == nil && p.Duration > 0 {
			seek = p.Duration * 0.1
		}
	}
	release, err := s.runner.AcquireLight(ctx)
	if err != nil {
		return err
	}
	defer release()
	jobDir, done, err := s.jobDir()
	if err != nil {
		return err
	}
	defer done()
	tmp := filepath.Join(jobDir, "thumb.jpg")
	attempt := func(seek float64) error {
		in, _, err := s.open(path)
		if err != nil {
			return err
		}
		defer in.File.Close()
		tctx, cancel := context.WithTimeout(ctx, s.cfg.ProbeTimeout.Duration)
		defer cancel()
		cmd := s.runner.Command(tctx, "ffmpeg", in, jobDir, func(input string) []string {
			args := []string{"-nostdin", "-hide_banner", "-loglevel", "error", "-y"}
			if seek > 0 {
				args = append(args, "-ss", strconv.FormatFloat(seek, 'f', 2, 64))
			}
			args = append(args, inputArgs(input)...)
			return append(args, "-map", "0:v:0", "-frames:v", "1",
				// Fit within the box without upscaling.
				"-vf", fmt.Sprintf("scale='min(%d,iw)':'min(%d,ih)':force_original_aspect_ratio=decrease", thumbSize, thumbSize),
				"-f", "image2", "-c:v", "mjpeg", "-q:v", "4", tmp)
		})
		_, err = run(cmd)
		return err
	}
	if err := attempt(seek); err != nil {
		if seek == 0 {
			return ErrNoThumbnail
		}
		if err := attempt(0); err != nil {
			return ErrNoThumbnail
		}
	}
	err = publish(tmp, out, func(f *os.File) error {
		cfg, err := jpeg.DecodeConfig(f)
		if err != nil || cfg.Width > thumbSize || cfg.Height > thumbSize {
			return errors.New("invalid thumbnail")
		}
		return nil
	})
	if errors.Is(err, ErrConvert) || errors.Is(err, os.ErrNotExist) {
		return ErrNoThumbnail
	}
	return err
}
