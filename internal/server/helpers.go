package server

import (
	"io/fs"
	"net/http"
	"os"
	"strconv"

	"filebrowser/internal/files"
	"filebrowser/internal/httpx"
)

// authorized cleans a client path and checks that the caller has want on it,
// writing the error response otherwise. It returns the real path.
func (s *Server) authorized(w http.ResponseWriter, r *http.Request, raw string, want files.Perm) (string, bool) {
	p, ok := httpx.CleanPath(w, r, raw)
	if !ok {
		return "", false
	}
	real, err := s.files.FS.Authorize(httpx.IdentityFrom(r.Context()).Access, p, want)
	if err != nil {
		httpx.FileError(w, r, err)
		return "", false
	}
	return real, true
}

// readableFile is authorized for reading a file that is not a directory.
func (s *Server) readableFile(w http.ResponseWriter, r *http.Request, raw string) (string, fs.FileInfo, bool) {
	p, ok := s.authorized(w, r, raw, files.PermRead)
	if !ok {
		return "", nil, false
	}
	fi, err := s.files.FS.Stat(p)
	if err == nil && fi.IsDir() {
		err = files.ErrIsDir
	}
	if err != nil {
		httpx.FileError(w, r, err)
		return "", nil, false
	}
	return p, fi, true
}

// fileOpts controls how serveFile presents user content.
type fileOpts struct {
	inline bool
	// allowPDF permits inline PDF (only on the share origin, which holds no session).
	allowPDF bool
	// frameAncestors, if set, may frame an inline PDF (the preview iframe).
	frameAncestors string
}

// serveFile serves a regular file with range support and safe headers.
func serveFile(w http.ResponseWriter, r *http.Request, fsys *files.FS, p string, o fileOpts) {
	f, fi, err := fsys.OpenFile(p)
	if err != nil {
		httpx.FileError(w, r, err)
		return
	}
	defer f.Close()
	ct := files.MimeType(fi.Name())
	inline := o.inline && files.InlineSafe(ct, o.allowPDF)
	httpx.UserContentHeaders(w, ct, inline, fi.Name())
	if inline && ct == "application/pdf" && o.frameAncestors != "" {
		w.Header().Del("X-Frame-Options")
		w.Header().Set("Content-Security-Policy", w.Header().Get("Content-Security-Policy")+"; frame-ancestors "+o.frameAncestors)
	}
	if w.Header().Get("Cache-Control") == "" {
		w.Header().Set("Cache-Control", "private, no-cache")
	}
	http.ServeContent(w, r, "", fi.ModTime(), f)
}

// serveOpened serves (and closes) a file the server opened itself, such as a
// cache entry. Headers must already be set.
func serveOpened(w http.ResponseWriter, r *http.Request, f *os.File) {
	defer f.Close()
	fi, err := f.Stat()
	if err != nil {
		httpx.InternalError(w, r, err)
		return
	}
	http.ServeContent(w, r, "", fi.ModTime(), f)
}

// serveCacheFile opens a server-generated cache path and serves it.
func serveCacheFile(w http.ResponseWriter, r *http.Request, path string) {
	f, err := os.Open(path) // #nosec G304 G703 -- cache path generated by the server
	if err != nil {
		httpx.FileError(w, r, files.ErrNotFound)
		return
	}
	serveOpened(w, r, f)
}

// serveZip streams a zip of the (authorized, real) paths. allow is consulted
// for the targets of symlinks found inside them.
func serveZip(w http.ResponseWriter, r *http.Request, fsys *files.FS, paths []string, allow func(real string) bool) {
	httpx.UserContentHeaders(w, "application/zip", false, zipName(paths))
	w.Header().Set("Cache-Control", "no-store")
	if err := fsys.WriteZip(r.Context(), w, paths, allow); err != nil {
		// Headers are already sent; abort the connection so the client sees a failure.
		panic(http.ErrAbortHandler)
	}
}

func zipName(paths []string) string {
	if len(paths) == 1 && paths[0] != "" {
		return files.Base(paths[0]) + ".zip"
	}
	return "download.zip"
}

func parseID(w http.ResponseWriter, r *http.Request) (int64, bool) {
	n, err := strconv.ParseInt(r.PathValue("id"), 10, 64)
	if err != nil || n <= 0 {
		httpx.Error(w, http.StatusNotFound, "not found")
		return 0, false
	}
	return n, true
}

// userKey is a rate-limit key scoped to one user.
func userKey(prefix string, userID int64) string { return prefix + ":" + strconv.FormatInt(userID, 10) }
